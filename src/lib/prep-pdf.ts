export async function downloadPrepPdf(): Promise<void> {
  const container = document.createElement("div");
  container.style.position = "absolute";
  container.style.left = "-9999px";
  container.style.top = "0";
  container.style.background = "#fff";
  container.innerHTML = buildPrepHtml();
  document.body.appendChild(container);

  try {
    const canvas = await html2canvas(
      container.firstElementChild as HTMLElement,
      {
        scale: 2,
        useCORS: true,
        backgroundColor: "#ffffff",
      }
    );

    const doc = new jsPDF({ unit: "pt", format: "a4" });
    const pageW = doc.internal.pageSize.getWidth();
    const pageH = doc.internal.pageSize.getHeight();
    const margin = 48;
    const availW = pageW - margin * 2;
    const availH = pageH - margin * 2;
    const pageCanvasH = Math.floor((availH / availW) * canvas.width);

    let offset = 0;
    let page = 0;
    while (offset < canvas.height) {
      const sliceH = Math.min(pageCanvasH, canvas.height - offset);
      const slice = document.createElement("canvas");
      slice.width = canvas.width;
      slice.height = sliceH;
      const ctx = slice.getContext("2d");
      if (!ctx) break;
      ctx.fillStyle = "#ffffff";
      ctx.fillRect(0, 0, slice.width, slice.height);
      ctx.drawImage(
        canvas,
        0,
        offset,
        canvas.width,
        sliceH,
        0,
        0,
        canvas.width,
        sliceH
      );

      if (page > 0) doc.addPage();
      doc.addImage(
        slice.toDataURL("image/png"),
        "PNG",
        margin,
        margin,
        availW,
        (sliceH / canvas.width) * availW
      );

      offset += sliceH;
      page += 1;
    }

    doc.save("colonoscopy-prep.pdf");
  } finally {
    document.body.removeChild(container);
  }
}
